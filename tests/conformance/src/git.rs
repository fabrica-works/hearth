#[derive(Clone, Copy, Debug)]
pub enum Kind {
    Revision(&'static str),
    Commit,
    Tree,
    Listing,
    Blobs,
    Missing,
    Diff(&'static Change),
}
#[derive(Clone, Copy, Debug)]
pub struct Case {
    pub name: &'static str,
    pub repository: usize,
    pub kind: Kind,
}
impl Case {
    #[must_use]
    pub fn is_listing(&self) -> bool {
        matches!(self.kind, Kind::Listing)
    }
}
